# D8: the X-Correlation-Id a client sends is reflected in the traceId of the errors the gateway
# generates and in the response header. Only [A-Za-z0-9._-]{1,64} is kept; anything else is replaced
# by a generated id, so a body is always valid JSON with no injected field.

long=$(printf 'a%.0s' $(seq 1 65))
valid64=$(printf 'b%.0s' $(seq 1 64))

check_response() {  # description, expected status, expected top-level keys, id sent
  expect "$1: status" "$2" "$STATUS"
  expect "$1: the body is a JSON object with only its own fields" "$3" "$(json_keys)"
  returned=$(header_value X-Correlation-Id)
  expect "$1: the header holds a safe id" 1 "$(printf '%s' "$returned" | grep -c '^[A-Za-z0-9._-]\{1,64\}$')"
  if [ "$4" = "$returned" ]; then
    pass "$1: a valid id is kept"
  elif printf '%s' "$4" | grep -q '^[A-Za-z0-9._-]\{1,64\}$'; then
    fail "$1: a valid id is kept" "sent '$4', got '$returned'"
  else
    expect "$1: an unsafe id is replaced by a generated one" 1 "$(printf '%s' "$returned" | grep -c '^[0-9a-f]\{32\}$')"
  fi
}

run_payload() {  # label, id
  fetch -H "X-Correlation-Id: $2" "$BASE/nope"
  check_response "404 with $1" 404 error,message,traceId "$2"
  expect "404 with $1: traceId equals the header" "$(header_value X-Correlation-Id)" "$(json_get traceId)"
  fetch -X POST -H "X-Correlation-Id: $2" "$BASE/api/v1/auth/logout"
  check_response "401 with $1" 401 error,message,traceId "$2"
  fetch -X POST -H "X-Correlation-Id: $2" "$BASE/api/v1/auth/internal/maintenance/purge"
  check_response "internal 404 with $1" 404 error,message,traceId "$2"
  fetch -H "X-Correlation-Id: $2" "$BASE/api/v1/catalog/billboard"
  check_response "503 (upstream failure) with $1" 503 error,message,traceId "$2"
  fetch -H "X-Correlation-Id: $2" "$BASE_ECHO/api/v1/auth/jwks"
  check_response "proxied response with $1" 200 authorization,correlationId,xUserId,xUserRoles "$2"
  expect "proxied response with $1: the service received the id the client got back" "$(header_value X-Correlation-Id)" "$(json_get correlationId)"
}

run_payload "a valid id" 'trace-1.A_b'
run_payload "a valid id of 64 characters" "$valid64"
run_payload "a quote that injects a field" 'x","injected":"1'
run_payload "a quote that breaks the JSON" 'x"'
run_payload "a backslash" 'x\'
run_payload "a backslash and quote" 'x\"y'
run_payload "a 65 character id" "$long"
run_payload "unicode" "caf$(printf '\303\251')-$(printf '\360\237\230\200')"
run_payload "a JSON tail" '"},{"injected":"1'
run_payload "spaces" 'a b'

# A line break in the value cannot create a response header: curl sends it as a second request header.
fetch -H "X-Correlation-Id: $(printf 'x\r\nX-Injected: 1')" "$BASE/nope"
expect "a CR/LF id does not create a header" 0 "$(header_count X-Injected)"
if [ "$STATUS" = 404 ]; then check_response "404 with CR/LF" 404 error,message,traceId x; else expect "a CR/LF id is refused by nginx" 400 "$STATUS"; fi

# Two X-Correlation-Id headers are not a valid single id.
fetch -H 'X-Correlation-Id: one' -H 'X-Correlation-Id: two' "$BASE/nope"
check_response "404 with two headers" 404 error,message,traceId 'one, two'

# The 429 and 504 answers are generated by the gateway too.
fetch_rate_limited 'X-Correlation-Id: x","injected":"1'
check_response "429 with an injection" 429 error,message,traceId 'x","injected":"1'
fetch -H 'X-Correlation-Id: x","injected":"1' "$BASE/api/v1/booking/health"
check_response "504 (upstream timeout) with an injection" 503 error,message,traceId 'x","injected":"1'
